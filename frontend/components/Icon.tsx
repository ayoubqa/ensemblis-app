export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  className?: string;
  /** Pixel size (default 18 via CSS `svg.i`). */
  size?: number;
  style?: CSSProperties;
  /** Accessible label; when omitted the icon is decorative (aria-hidden). */
  label?: string;
  strokeWidth?: number;
}

/** Prototype `ic(name)` — renders <svg class="i">. */
export function Icon({ name, className, size, style, label, strokeWidth }: IconProps) {
  const s: CSSProperties = { ...(size ? { width: size, height: size } : null), ...(strokeWidth ? { strokeWidth } : null), ...style };
  return (
    <svg
      className={className ? `i ${className}` : "i"}
      viewBox="0 0 24 24"
      style={s}
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true, focusable: "false" })}
      dangerouslySetInnerHTML={{ __html: ICONS[name] || "" }}
    />
  );
}

